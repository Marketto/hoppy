def licenses_html(data: dict, lang: str, platforms: set[str] | None) -> tuple[str, str]:
    t = UI[lang]
    e = html.escape
    comps = [c for c in data["components"] if platforms is None or set(c["platforms"]) & platforms]
    used = [lid for lid in data["licenses"] if any(lid in c["applies"] for c in comps)]
    count = {lid: sum(lid in c["applies"] for c in comps) for lid in used}
    out = [f"<p>{t['lic_intro'].format(copyright=e(data['project']['copyright']), url=e(data['project']['url']))}</p>",
           f'<h2 id="summary">{t["summary"]}</h2>',
           f'<div class="table-wrap" role="region" tabindex="0" aria-label="{t["summary"]}"><table>'
           f'<thead><tr><th scope="col">{t["licence"]}</th><th scope="col">{t["components"]}</th></tr></thead><tbody>']
    out += [f'<tr><td><a href="#lic-{slug(lid)}">{e(data["licenses"][lid]["name"])}</a></td><td>{count[lid]}</td></tr>'
            for lid in used]
    out.append("</tbody></table></div>")
    for kind in ("rust", "android", "font"):
        rows = [c for c in comps if c["kind"] == kind]
        if not rows:
            continue
        out.append(f'<h2 id="{kind}">{e(t[kind])}</h2>')
        out.append(f'<div class="table-wrap" role="region" tabindex="0" aria-label="{e(t[kind])}"><table><thead><tr>'
                   + "".join(f'<th scope="col">{t[k]}</th>' for k in ("name", "version", "declared", "used", "platforms"))
                   + "</tr></thead><tbody>")
        for c in rows:
            plats = ", ".join(PLATFORM[p] for p in c["platforms"] if platforms is None or p in platforms)
            out.append(f'<tr><td><a href="{e(c["url"])}">{e(c["name"])}</a></td><td>{e(c["version"]) or "—"}</td>'
                       f'<td>{e(c["license"])}</td><td>{e(" AND ".join(c["applies"]))}</td><td>{e(plats)}</td></tr>')
        out.append("</tbody></table></div>")
    out += [f'<h2 id="original">{t["original"]}</h2>', f"<p>{t['original_text']}</p>",
            f'<h2 id="not-distributed">{t["not_dist"]}</h2>', f"<p>{t['not_dist_text']}</p>",
            f'<h2 id="notices">{t["notices"]}</h2>']
    for lid in used:
        lic = data["licenses"][lid]
        out.append(f'<h3 id="lic-{slug(lid)}">{e(lic["name"])}</h3>')
        out.append(f"<p>{t['used_by'].format(n=count[lid])}</p><ul class=\"notices\">")
        for c in comps:
            if lid in c["applies"]:
                label = f"{c['name']} {c['version']}".strip()
                out.append(f"<li><strong>{e(label)}</strong>: {e('; '.join(c['copyright']))}</li>")
        out.append("</ul>")
        out.append(f'<pre lang="en">{e(lic["text"])}</pre>')
    names = {f"{c['name']} {c['version']}".strip() for c in comps}
    notices = [n for n in data["notices"] if n["component"] in names]
    if notices:
        out += [f'<h2 id="notice-files">{t["notice_files"]}</h2>', f"<p>{t['notice_intro']}</p>"]
        for n in notices:
            out += [f"<h3>{e(n['component'])}</h3>", f'<pre lang="en">{e(n["text"])}</pre>']
    return t["lic_title"], "\n".join(out)


