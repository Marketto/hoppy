# ---------------------------------------------------------------- Markdown subset

INLINE = re.compile(r"`([^`]+)`|<(https?://[^>\s]+)>|\[([^\]]+)\]\(([^)\s]+)\)|\*\*(.+?)\*\*|\*([^*\s][^*]*)\*")


def slug(text: str) -> str:
    text = re.sub(r"<[^>]+>", "", text).lower()
    return re.sub(r"[^\w]+", "-", text).strip("-")


def link_target(url: str, lang: str) -> str:
    if re.match(r"https?://", url):
        return url
    name = url.split("#")[0]
    frag = url[len(name):]
    if name == "third-party-licenses.md":
        return f"licenses.{lang}.html{frag}"
    m = re.fullmatch(r"(terms|privacy)\.(it|en)\.md", name)
    if m:
        return f"{m.group(1)}.{m.group(2)}.html{frag}"
    sys.exit(f"✗ legal: unsupported link target {url!r} (only the other legal pages or https:// URLs)")


def inline(text: str, lang: str) -> str:
    out, pos = [], 0
    for m in INLINE.finditer(text):
        out.append(html.escape(text[pos:m.start()], quote=False))
        code, auto, label, url, bold, ital = m.groups()
        if code is not None:
            out.append(f"<code>{html.escape(code, quote=False)}</code>")
        elif auto is not None:
            out.append(f'<a href="{html.escape(auto)}">{html.escape(auto, quote=False)}</a>')
        elif label is not None:
            out.append(f'<a href="{html.escape(link_target(url, lang))}">{inline(label, lang)}</a>')
        elif bold is not None:
            out.append(f"<strong>{inline(bold, lang)}</strong>")
        else:
            out.append(f"<em>{inline(ital, lang)}</em>")
        pos = m.end()
    out.append(html.escape(text[pos:], quote=False))
    return "".join(out)


def markdown(md: str, lang: str) -> tuple[str, str]:
    """→ (title from the `#` heading, HTML fragment of the rest)."""
    lines = re.sub(r"<!--.*?-->", "", md, flags=re.S).split("\n")
    out: list[str] = []
    title = ""
    heading = ""
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        m = re.match(r"(#{1,3}) (.*)", line)
        if m:
            level, text = len(m.group(1)), m.group(2).strip()
            if level == 1 and not title:
                title = text
            else:
                heading = text
                out.append(f'<h{level} id="{slug(text)}">{inline(text, lang)}</h{level}>')
            i += 1
            continue
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            head, body = rows[0], [r for r in rows[1:] if not all(re.fullmatch(r":?-+:?", c) for c in r)]
            t = ['<div class="table-wrap" role="region" tabindex="0" '
                 f'aria-label="{html.escape(heading or title)}"><table>',
                 "<thead><tr>" + "".join(f'<th scope="col">{inline(c, lang)}</th>' for c in head) + "</tr></thead>",
                 "<tbody>"]
            t += ["<tr>" + "".join(f"<td>{inline(c, lang)}</td>" for c in r) + "</tr>" for r in body]
            out.append("\n".join(t + ["</tbody></table></div>"]))
            continue
        lm = re.match(r"(\s*)(-|\d+\.) ", line)
        if lm:
            tag = "ul" if lm.group(2) == "-" else "ol"
            items: list[str] = []
            while i < len(lines):
                cur = lines[i]
                im = re.match(r"(\s*)(-|\d+\.) (.*)", cur)
                if im and ((im.group(2) == "-") == (tag == "ul")) and len(im.group(1)) == len(lm.group(1)):
                    items.append(im.group(3).strip())
                elif cur.strip() and cur.startswith(" ") and items:
                    items[-1] += " " + cur.strip()
                else:
                    break
                i += 1
            out.append(f"<{tag}>" + "".join(f"<li>{inline(it, lang)}</li>" for it in items) + f"</{tag}>")
            continue
        para = []
        while i < len(lines) and lines[i].strip() and not re.match(r"#{1,3} |\||\s*(-|\d+\.) ", lines[i]):
            para.append(lines[i].strip())
            i += 1
        out.append(f"<p>{inline(' '.join(para), lang)}</p>")
    return title, "\n".join(out)


# ---------------------------------------------------------------- Plain text

def plain_inline(text: str, lang: str) -> str:
    def sub(m: re.Match) -> str:
        code, auto, label, url, bold, ital = m.groups()
        if code is not None:
            return code
        if auto is not None:
            return auto
        if label is not None:
            target = link_target(url, lang)
            if not re.match(r"https?://", target):
                target = PORTAL_LEGAL + target
            return f"{plain_inline(label, lang)} ({target})"
        return plain_inline(bold if bold is not None else ital, lang)
    return INLINE.sub(sub, text)


def plain_text(md: str, lang: str) -> str:
    """The same Markdown subset as `markdown`, as wrapped plain text (installer licence page)."""
    import textwrap
    lines = re.sub(r"<!--.*?-->", "", md, flags=re.S).split("\n")
    out: list[str] = []

    def wrap(s: str, first: str = "", rest: str = "") -> str:
        return textwrap.fill(s, width=78, initial_indent=first, subsequent_indent=rest, break_long_words=False,
                             break_on_hyphens=False)
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        m = re.match(r"(#{1,3}) (.*)", line)
        if m:
            text = plain_inline(m.group(2).strip(), lang)
            out.append(text.upper() if len(m.group(1)) == 1 else text)
            out.append(("=" if len(m.group(1)) == 1 else "-") * len(text))
            i += 1
            continue
        if line.startswith("|"):
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-+:?", c) for c in cells):
                    out.append(wrap(" | ".join(plain_inline(c, lang) for c in cells), "  ", "    "))
                i += 1
            out.append("")
            continue
        lm = re.match(r"(\s*)(-|\d+\.) ", line)
        if lm:
            items: list[tuple[str, str]] = []
            while i < len(lines):
                cur = lines[i]
                im = re.match(r"(\s*)(-|\d+\.) (.*)", cur)
                if im and len(im.group(1)) == len(lm.group(1)):
                    items.append(("•" if im.group(2) == "-" else im.group(2), im.group(3).strip()))
                elif cur.strip() and cur.startswith(" ") and items:
                    items[-1] = (items[-1][0], items[-1][1] + " " + cur.strip())
                else:
                    break
                i += 1
            for mark, item in items:
                out.append(wrap(plain_inline(item, lang), f"  {mark} ", " " * (len(mark) + 3)))
            out.append("")
            continue
        para = []
        while i < len(lines) and lines[i].strip() and not re.match(r"#{1,3} |\||\s*(-|\d+\.) ", lines[i]):
            para.append(lines[i].strip())
            i += 1
        out.append(wrap(plain_inline(" ".join(para), lang)))
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def terms_text(md: str, lang: str) -> str:
    t = TEXT_UI[lang]
    links = "\n".join(f"  {label}: {PORTAL_LEGAL}{doc}.{lang}.html" for doc, label in
                      (("terms", t["online"]), ("privacy", t["privacy"]), ("licenses", t["licenses"])))
    # BOM: Inno Setup reads a .txt licence file as UTF-8 only with it.
    import textwrap
    return "\ufeff" + textwrap.fill(t["intro"], width=78) + "\n\n" + plain_text(md, lang) + "\n" + "-" * 78 + "\n" + links + "\n"


