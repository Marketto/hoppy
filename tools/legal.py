def load() -> tuple[dict, dict, dict, dict]:
    version = json.loads((SRC / "version.json").read_text(encoding="utf-8"))
    strings = json.loads((SRC / "strings.json").read_text(encoding="utf-8"))
    licenses = json.loads((SRC / "third-party-licenses.json").read_text(encoding="utf-8"))
    docs = {}
    for doc in ("terms", "privacy"):
        for lang in LANGS:
            md = (SRC / f"{doc}.{lang}.md").read_text(encoding="utf-8")
            docs[(doc, lang, "md")] = md
            word = "Versione" if lang == "it" else "Version"
            if not re.search(rf"\*\*{word} {version[doc]} — ", md):
                sys.exit(f"✗ legal: docs/legal/{doc}.{lang}.md must say '**{word} {version[doc]} — <date>**' "
                         "(docs/legal/version.json)")
            docs[(doc, lang)] = markdown(md, lang)
    if set(strings) != set(LANGS) or set(strings["it"]) != set(strings["en"]):
        sys.exit("✗ legal: docs/legal/strings.json needs the same keys in it and en")
    return version, strings, licenses, docs


def outputs() -> dict[Path, str]:
    version, strings, licenses, docs = load()
    files: dict[Path, str] = {}
    for lang in LANGS:
        for doc in DOCS:
            title, body = docs[(doc, lang)] if doc != "licenses" else licenses_html(licenses, lang, None)
            files[SITE_OUT / f"{doc}.{lang}.html"] = site_page(doc, lang, title, body, strings)
            for out_dir, platforms in APPS.items():
                if doc == "licenses":
                    title, body = licenses_html(licenses, lang, platforms)
                files[out_dir / f"{doc}.{lang}.html"] = app_page(doc, lang, title, body, strings)
    bundle = {"version": version, "strings": strings,
              "pages": {doc: {lang: f"{doc}.{lang}.html" for lang in LANGS} for doc in DOCS}}
    for out_dir in APPS:
        files[out_dir / "legal.json"] = json.dumps(bundle, ensure_ascii=False, indent=1) + "\n"
    for lang in LANGS:
        files[TEXT_OUT / f"terms.{lang}.txt"] = terms_text(docs[("terms", lang, "md")], lang)
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if an output is missing or out of date")
    a = ap.parse_args()
    files = outputs()
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if a.check:
        if stale:
            print("✗ legal pages out of date (run `python3 tools/legal.py`): "
                  + ", ".join(str(p.relative_to(ROOT)) for p in stale))
            return 1
        print(f"✓ legal pages up to date ({len(files)} files)")
        return 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    print(f"✓ legal pages: {len(stale)} written, {len(files) - len(stale)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
